// ============================================================================
// Helpers
// ======================================================================================

type options struct {
	init          bool
	ignoreMethods bool
}

func writeVar(
	w io.Writer, rs []requireableGroup, name string,
	writeSymbolType func(w io.Writer, indentation int, chain []string, s requireableSymbol),
	writeSymbolValue func(w io.Writer, indentation int, chain []string, s requireableSymbol),
	o options,
) {
	fmt.Fprint(w, "var "+name+" ")
	if !o.init {
		fmt.Fprint(w, "= ")
	}
	writeType(w, 0, rs, writeSymbolType, o)

	indentation := 0
	if o.init {
		fmt.Fprintln(w)
		fmt.Fprintln(w, "func init() {")

		fmt.Fprint(w, "\t"+name+" = ")
		writeType(w, 1, rs, writeSymbolType, o)
		indentation = 1
	}

	indent := strings.Repeat("\t", indentation)

	fmt.Fprintln(w, "{")
	for _, r := range rs {
		fmt.Fprint(w, indent+"\t"+r.Name+": ")
		writeGroupValue(w, indentation+1, []string{r.Name}, r, writeSymbolType, writeSymbolValue, o)
		fmt.Fprintln(w, ",")
	}
	fmt.Fprintln(w, indent+"}")

	if o.init {
		fmt.Fprintln(w, "}")
	}
}

func writeType(
	w io.Writer, indentation int, rs []requireableGroup,
	writeSymbolType func(w io.Writer, indentation int, chain []string, s requireableSymbol),
	o options,
) {
	indent := strings.Repeat("\t", indentation)

	fmt.Fprintln(w, "struct {")
	for _, r := range rs {
		fmt.Fprint(w, indent+"\t"+r.Name+" ")
		writeGroupType(w, indentation+1, []string{r.Name}, r, writeSymbolType, o)
		fmt.Fprintln(w)
	}
	fmt.Fprint(w, indent+"}")
}

func writeGroupType(
	w io.Writer, indentation int, chain []string, r requireableGroup,
	writeSymbolType func(w io.Writer, indentation int, chain []string, s requireableSymbol),
	o options,
) {
	indent := strings.Repeat("\t", indentation)

	fmt.Fprintln(w, "struct {")
	for _, s := range r.Symbols {
		if o.ignoreMethods && s.Method {
			continue
		}
		fmt.Fprint(w, indent+"\t"+s.Name+" ")
		writeSymbolType(w, indentation+1, append(chain, s.Name), s)
		fmt.Fprintln(w)
	}
	for _, f := range r.Fields {
		fmt.Fprint(w, indent+"\t"+f.Name+" ")
		writeGroupType(w, indentation+1, append(chain, f.Name), f, writeSymbolType, o)
		fmt.Fprintln(w)
	}
	fmt.Fprint(w, indent+"}")
}

func writeGroupValue(
	w io.Writer, indentation int, chain []string, g requireableGroup,
	writeSymbolType func(w io.Writer, indentation int, chain []string, s requireableSymbol),
	writeSymbolValue func(w io.Writer, indentation int, chain []string, s requireableSymbol),
	o options,
) {
	indent := strings.Repeat("\t", indentation)

	writeGroupType(w, indentation, chain, g, writeSymbolType, o)
	fmt.Fprintln(w, "{")
	for _, s := range g.Symbols {
		if o.ignoreMethods && s.Method {
			continue
		}
		fmt.Fprint(w, indent+"\t"+s.Name+": ")
		writeSymbolValue(w, indentation+1, append(chain, s.Name), s)
		fmt.Fprintln(w, ",")
	}
	for _, f := range g.Fields {
		fmt.Fprint(w, indent+"\t"+f.Name+": ")
		writeGroupValue(w, indentation+1, append(chain, f.Name), f, writeSymbolType, writeSymbolValue, o)
		fmt.Fprintln(w, ",")
	}
	fmt.Fprint(w, indent+"}")
}
