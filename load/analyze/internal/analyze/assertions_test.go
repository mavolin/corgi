func writeRequireVar(w io.Writer, rs []requireableGroup) {
	writeVar(w, rs, "require", writeRequirerSymbolType, writeRequirerSymbolValue, options{
		init: true,
	})
}

func writeRequirerSymbolType(w io.Writer, _ int, chain []string, _ requireableSymbol) {
	rootType := chain[0]

	fmt.Fprint(w, "func(*analyzer, *file."+rootType+")")
}

func writeRequirerSymbolValue(w io.Writer, _ int, chain []string, _ requireableSymbol) {
	fmt.Fprint(w, "requirer{}."+strings.Join(chain, "_"))
}

