func writeAnalyzedVar(w io.Writer, rs []requireableGroup) {
	writeVar(w, rs, "analyzed", writeMarkSymbolType, writeMarkSymbolValue, options{
		ignoreMethods: true,
	})
}

func writeMarkSymbolType(w io.Writer, _ int, chain []string, _ requireableSymbol) {
	rootType := chain[0]

	fmt.Fprint(w, "func(z *analyzer, __r *file."+rootType+")")
}

func writeMarkSymbolValue(w io.Writer, indentation int, chain []string, s requireableSymbol) {
	indent := strings.Repeat("\t", indentation)

	writeMarkSymbolType(w, indentation, chain, s)
	fmt.Fprintln(w, " {")

	fmt.Fprint(w, indent+"\tz.Ran(__r, ")
	writeRequireKey(w, chain)
	fmt.Fprintln(w, ")")

	fmt.Fprint(w, indent+"}")
}

