func TestGenerateAssertions(t *testing.T) {
	requirers, err := loadRequirers()
	if err != nil {
		t.Fatalf("failed to load requirers: %v", err)
	}

	f, err := os.Create("assertions.go")
	if err != nil {
		t.Fatalf("failed to create assertions.go: %v", err)
	}

	pkgName := os.Getenv("GOPACKAGE")
	if pkgName == "" {
		t.Fatal("GOPACKAGE is not set")
	}

	fmt.Fprintln(f, "package "+pkgName)
	fmt.Fprintln(f)
	fmt.Fprintln(f, "import (")
	fmt.Fprintln(f, "\t\"github.com/mavolin/corgi/v2/escape/attrtype\"")
	fmt.Fprintln(f, "\t\"github.com/mavolin/corgi/v2/escape/elemtype\"")
	fmt.Fprintln(f, "\t\"github.com/mavolin/corgi/v2/file\"")
	fmt.Fprintln(f, "\t\"github.com/mavolin/corgi/v2/file/ast\"")
	fmt.Fprintln(f, ")")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "// Code generated by go test -run GenerateAssertions -tags generate; DO NOT EDIT.")
	fmt.Fprintln(f, "")
	fmt.Fprintln(f, "//go:generate go test -run GenerateAssertions -tags generate")
	fmt.Fprintln(f)
	writeGetVar(f, requirers)
	fmt.Fprintln(f)
	writeRequireVar(f, requirers)
	fmt.Fprintln(f)
	fmt.Fprintln(f, "type analyzedFileSymbol string")
	fmt.Fprintln(f)
	writeAnalyzedVar(f, requirers)
	fmt.Fprintln(f)
	writeRequireFieldVar(f, requirers)

	if err := f.Close(); err != nil {
		t.Fatalf("failed to close assertions.go: %v", err)
	}
}

// ============================================================================
// get
// ======================================================================================

func writeGetVar(w io.Writer, rs []requireableGroup) {
	writeVar(w, rs, "get", writeGetSymbolType, writeGetter, options{})
}

func writeGetSymbolType(w io.Writer, _ int, chain []string, s requireableSymbol) {
	rootType := chain[0]

	fmt.Fprint(w, "func(z *analyzer, __r *file.")
	fmt.Fprint(w, rootType)
	for _, p := range s.Params {
		fmt.Fprint(w, ", "+p[0]+" "+p[1])
	}
	fmt.Fprint(w, ") ")
	fmt.Fprint(w, s.Type)
}

func writeGetter(w io.Writer, indentation int, chain []string, s requireableSymbol) {
	indent := strings.Repeat("\t", indentation)

	writeGetSymbolType(w, indentation, chain, s)
	fmt.Fprintln(w, " {")

	fmt.Fprintln(w, indent+"\trequire."+strings.Join(chain, ".")+"(z, __r)")

	fmt.Fprint(w, indent+"\treturn __r."+strings.Join(chain[1:], "."))
	if s.Method {
		fmt.Fprint(w, "(")
		for i, p := range s.Params {
			if i > 0 {
				fmt.Fprint(w, ", ")
			}
			fmt.Fprint(w, p[0])
		}
		fmt.Fprint(w, ")")
	}
	fmt.Fprintln(w)

	fmt.Fprint(w, indent+"}")
}

// ============================================================================
